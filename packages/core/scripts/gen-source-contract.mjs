// Emit dist/source-contract.cjs from the canonical TypeScript constants in src/source-constants.ts.
//
// @reticlehq/babel-plugin is plain CommonJS tooling — Babel loads a plugin with `require()` — so it
// cannot import core's ESM build. Before this generator it declared its own copy of the attribute
// name, and the only thing holding the two together was a comment on each side pointing at the
// other. Drift there breaks all source mapping on the React 19 / Next SWC path, silently: the
// browser reads the attribute core names, the plugin writes the one it names itself, and every test
// still passes.
//
// Generating removes the copy rather than policing it, exactly as gen-desktop-contract.mjs does for
// the Electron preload. The two renderers are near-identical; kept separate because their emitted
// header text describes different contracts, and the issue asked not to widen the change.
//
// `renderSourceContract` is a pure function over its input so the parity test can call it with the
// constants straight from src (no dist needed). The CLI entry feeds it the built dist and writes.

/** Render the CommonJS module text for a `name → value` record. */
export function renderSourceContract(contract) {
  const lines = Object.entries(contract).map(
    ([name, value]) => `exports.${name} = ${JSON.stringify(value)};`,
  );
  return [
    '// GENERATED by scripts/gen-source-contract.mjs — do not edit.',
    '//',
    '// The CommonJS view of the source-mapping contract, for build tooling that Babel loads with',
    '// require() and which cannot import the ESM build. Edit src/source-constants.ts and rebuild',
    '// @reticlehq/core.',
    "'use strict';",
    ...lines,
    'Object.freeze(exports);',
    '',
  ].join('\n');
}

/** Render the CJS type declaration (.d.cts) for a `name → value` record. */
export function renderSourceContractDts(contract) {
  const lines = Object.entries(contract).map(
    ([name, value]) => `export declare const ${name}: ${JSON.stringify(value)};`,
  );
  return ['// GENERATED by scripts/gen-source-contract.mjs — do not edit.', ...lines, ''].join(
    '\n',
  );
}

// ── CLI entry ────────────────────────────────────────────────────────────────────────────────────
//
// `fileURLToPath(import.meta.url) === process.argv[1]` and `pathToFileURL` for the dynamic import,
// both for the Windows reasons spelled out at length in gen-desktop-contract.mjs: the string
// concatenation form never matches on Windows, so the generator silently no-ops and the package
// ships without the file something requires at boot.
const { fileURLToPath } = await import('node:url');
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { writeFileSync } = await import('node:fs');
  const { join, dirname } = await import('node:path');
  const { pathToFileURL } = await import('node:url');

  const here = dirname(fileURLToPath(import.meta.url));
  const dist = join(here, '..', 'dist');
  const { SOURCE_CONTRACT } = await import(pathToFileURL(join(dist, 'source-constants.js')).href);
  writeFileSync(join(dist, 'source-contract.cjs'), renderSourceContract(SOURCE_CONTRACT), 'utf8');
  writeFileSync(
    join(dist, 'source-contract.d.cts'),
    renderSourceContractDts(SOURCE_CONTRACT),
    'utf8',
  );
  // stderr, not stdout: this runs in `prepack`, where stdout corrupts the machine-readable output
  // of the command that triggered the pack.
  process.stderr.write(
    `wrote source contract (${String(Object.keys(SOURCE_CONTRACT).length)} constant) to dist/source-contract.{cjs,d.cts}\n`,
  );
}
