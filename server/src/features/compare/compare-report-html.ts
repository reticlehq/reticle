/**
 * `reticle compare --report <file>`: the comparison as one HTML page a person opens, shares or attaches to CI. It is
 * built from the `--json` object, so the page and the JSON never disagree. It is self-contained: no script, no external
 * style, no font. Every value is escaped, because the lines come from the pages under test: a page that shows
 * `<script>` must not run it inside the report.
 */
import { CompareVerdict } from './behaviour-diff.js';
import type { BehaviourDifference } from './behaviour-diff.js';
import { DifferenceKind } from './compare-diff.js';
import type { compareReportJson } from './behaviour-report.js';

type CompareReport = ReturnType<typeof compareReportJson>;

export const REPORT_TITLE = 'Reticle compare';
const TXT = {
  reference: 'Reference',
  candidate: 'Candidate',
  base: 'Base',
  compared: 'sequences compared',
  ignored: 'lines ignored (they also changed between two runs of the reference)',
  unstable: 'not compared: the reference did not do them the same way twice',
  referenceFailed: 'not compared: the reference could not do them',
  steps: 'Steps',
  onlyReference: 'Only the reference shows',
  onlyCandidate: 'Only the candidate shows',
  unreached: 'The candidate could not do this step',
  same: 'No difference in what users see, in the sequences compared.',
  invalid: 'This run proves nothing, so nothing was proved. Reason:',
  generated: 'Generated by reticle compare. Nothing was installed in either app.',
} as const;

const VERDICT_TEXT: Record<string, string> = {
  [CompareVerdict.SAME]: 'SAME',
  [CompareVerdict.DIFFERENT]: 'DIFFERENT',
  [CompareVerdict.INVALID]: 'INVALID',
};

/** Design values, in one place (the report is outside the app's design system). */
const STYLE = `
:root { --bg:#fbfbfa; --fg:#1c1c1a; --muted:#6b6b66; --line:#e4e3df; --card:#ffffff;
  --same:#1f7a45; --diff:#b42318; --invalid:#8a6d00; --add-bg:#e9f6ee; --rem-bg:#fdecec; --mono:ui-monospace,SFMono-Regular,Menlo,monospace; }
@media (prefers-color-scheme: dark) { :root { --bg:#141413; --fg:#ecebe7; --muted:#a3a29c; --line:#2c2c29; --card:#1c1c1a;
  --same:#4cc27e; --diff:#ff7b6b; --invalid:#e0c04a; --add-bg:#16301f; --rem-bg:#3a1a17; } }
* { box-sizing:border-box } body { margin:0; background:var(--bg); color:var(--fg); font:15px/1.5 system-ui,sans-serif }
main { max-width:960px; margin:0 auto; padding:24px 16px 48px }
h1 { font-size:20px; margin:0 0 4px } .verdict { font-weight:700; letter-spacing:.04em }
.SAME { color:var(--same) } .DIFFERENT { color:var(--diff) } .INVALID { color:var(--invalid) }
.urls, .counts { color:var(--muted); margin:4px 0 } .urls code { color:var(--fg); overflow-wrap:anywhere }
.card { background:var(--card); border:1px solid var(--line); border-radius:8px; padding:12px 14px; margin:14px 0 }
.card h2 { font-size:14px; margin:0 0 6px; color:var(--muted) }
ol.steps { margin:4px 0 8px 18px; padding:0 } pre { margin:4px 0; padding:8px; border-radius:6px; white-space:pre-wrap;
  overflow-wrap:anywhere; font:13px/1.45 var(--mono) } .rem { background:var(--rem-bg) } .add { background:var(--add-bg) }
.side { font-size:13px; color:var(--muted); margin-top:6px } footer { color:var(--muted); font-size:13px; margin-top:28px }
`;

const esc = (s: unknown): string =>
  String(s)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');

function differenceCard(d: BehaviourDifference, n: number): string {
  const steps = `<ol class="steps">${d.actions.map((a) => `<li>${esc(a)}</li>`).join('')}</ol>`;
  const seen = `Seen in ${String(d.seen)} sequence${1 === d.seen ? '' : 's'}`;
  if (d.kind === DifferenceKind.UNREACHED) {
    return `<section class="card"><h2>#${String(n)} · ${esc(seen)}</h2><div class="side">${TXT.steps}</div>${steps}<div class="side">${TXT.unreached}</div><pre class="rem">${esc(d.failedAt ?? '')}</pre></section>`;
  }
  const side = (label: string, cls: string, lines: readonly string[]): string =>
    0 === lines.length
      ? ''
      : `<div class="side">${label}</div><pre class="${cls}">${esc(lines.join('\n'))}</pre>`;
  return `<section class="card"><h2>#${String(n)} · ${esc(seen)}</h2><div class="side">${TXT.steps}</div>${steps}${side(TXT.onlyReference, 'rem', d.removed)}${side(TXT.onlyCandidate, 'add', d.added)}</section>`;
}

/** The report page for one comparison. */
export function compareReportHtml(report: CompareReport): string {
  const verdict = VERDICT_TEXT[report.verdict] ?? String(report.verdict);
  const urls = [
    `${TXT.reference}: <code>${esc(report.reference)}</code>`,
    `${TXT.candidate}: <code>${esc(report.candidate)}</code>`,
    ...(report.base === undefined ? [] : [`${TXT.base}: <code>${esc(report.base)}</code>`]),
  ];
  const counts = [
    `<b>${String(report.compared)}</b> of ${String(report.sequences)} ${TXT.compared}`,
    `<b>${String(report.ignored)}</b> ${TXT.ignored}`,
    ...(report.unstable > 0 ? [`<b>${String(report.unstable)}</b> ${TXT.unstable}`] : []),
    ...(report.referenceFailed > 0
      ? [`<b>${String(report.referenceFailed)}</b> ${TXT.referenceFailed}`]
      : []),
  ];
  let body: string;
  if (report.verdict === CompareVerdict.INVALID) {
    body = `<section class="card"><p>${TXT.invalid}</p><pre>${esc(report.reason ?? '')}</pre></section>`;
  } else if (0 === report.differences.length) {
    body = `<section class="card"><p>${TXT.same}</p></section>`;
  } else {
    body = report.differences.map((d, i) => differenceCard(d, i + 1)).join('\n');
  }
  return [
    '<!doctype html>',
    '<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
    `<title>${REPORT_TITLE}: ${verdict}</title><style>${STYLE}</style></head><body><main>`,
    `<h1>${REPORT_TITLE}: <span class="verdict ${verdict}">${verdict}</span></h1>`,
    ...urls.map((u) => `<p class="urls">${u}</p>`),
    `<p class="counts">${counts.join(' · ')}</p>`,
    body,
    `<footer>${TXT.generated}</footer>`,
    '</main></body></html>',
  ].join('\n');
}
